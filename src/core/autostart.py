"""开机自启（Windows）。

**为什么不能用 Run 键**：本程序的 exe 内嵌了 ``requireAdministrator`` 清单
（连 WiFi、按网卡读流量统计都需要管理员权限）。而 Windows 出于安全考虑，
**会静默跳过 Run 键里需要提权的程序** —— 用户看不到任何提示，程序也不会启动。
这一条踩过坑：注册表里 ``CampusNet = "...\\CampusNet.exe" --minimized`` 明明写着，
开机就是不启动。

**正确做法是计划任务**：

* 触发器：登录时（``/SC ONLOGON``）
* 运行级别：最高权限（``/RL HIGHEST``）→ 提权启动且**不弹 UAC**
* 动作：``"<exe>" --minimized``

``schtasks`` 创建"以当前用户身份、最高权限"的任务不需要额外提权；
本程序本身就是提权运行的，所以这条路一定走得通。

Run 键仍然保留为**退路**：万一计划任务被组策略禁用，至少写一条 Run 项
（源码方式运行时没有 UAC 清单，Run 键是有效的）。
"""

from __future__ import annotations

import os
import subprocess
import sys

TASK_NAME = "CampusNet"
RUN_KEY = "Software\\Microsoft\\Windows\\CurrentVersion\\Run"
RUN_VALUE = "CampusNet"


def launch_command() -> tuple[str, str]:
    """返回 (命令行, exe 所在目录)。

    开机跑的是**无界面自连程序**（``--connect-only``）：连上校园网 → 发通知 →
    把主程序拉起来 → 自己退出。所以这里不带 ``--minimized``：是否隐藏窗口由
    主程序读「启动后最小化」配置自己决定。

    ⚠ 优先用**目录版**：单文件版每次启动都要把 120+ MB 解压到临时目录（实测好几秒），
    而"开机尽快联网"这件事每一秒都算数。同目录下有 ``CampusNet-portable`` 就直接用它。
    """
    if getattr(sys, "frozen", False):
        exe = sys.executable
        folder = os.path.dirname(exe)
        fast = os.path.join(folder, "CampusNet-portable", "CampusNet-portable.exe")
        if os.path.exists(fast):
            return f'"{fast}" --connect-only', os.path.dirname(fast)
        return f'"{exe}" --connect-only', folder
    entry = os.path.join(
        os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
        "main.py",
    )
    return f'"{sys.executable}" "{entry}" --connect-only', os.path.dirname(entry)


def _schtasks(*args: str, timeout: float = 20.0) -> tuple[int, str]:
    """调用 schtasks，返回 (退出码, 合并输出)。"""
    try:
        proc = subprocess.run(["schtasks", *args], capture_output=True, timeout=timeout)
    except (OSError, subprocess.SubprocessError) as exc:
        return 1, f"{type(exc).__name__}: {exc}"
    raw = proc.stdout or proc.stderr or b""
    for encoding in ("gbk", "utf-8"):
        try:
            return proc.returncode, raw.decode(encoding)
        except UnicodeDecodeError:
            continue
    return proc.returncode, raw.decode("utf-8", errors="replace")


def task_exists() -> bool:
    code, _ = _schtasks("/Query", "/TN", TASK_NAME)
    return code == 0


def run_value() -> str:
    try:
        import winreg
        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, RUN_KEY) as key:
            value, _type = winreg.QueryValueEx(key, RUN_VALUE)
            return str(value)
    except Exception:
        return ""


def state() -> dict:
    """当前真实的自启状态（不读配置，直接查系统）。"""
    command, _cwd = launch_command()
    value = run_value()
    return {
        "task": task_exists(),
        "run_key": bool(value),
        "run_value": value,
        "expected": command,
        "enabled": task_exists() or bool(value),
    }


def launcher_script() -> str:
    """写一个 ``.cmd`` 启动器，返回它的路径。

    计划任务的 ``/TR`` 只支持"程序 + 参数"，遇到**带空格的路径 + 内层引号**时
    （例如 ``"python.exe" "…\\main.py" --minimized``）schtasks 会报
    ``Invalid argument/option``。让任务指向一个 .cmd、参数留空，
    就彻底没有引号问题。
    """
    command, _cwd = launch_command()
    candidates = [
        os.path.join(os.environ.get("APPDATA") or "", "CampusNet"),
        os.path.join(os.environ.get("LOCALAPPDATA") or "", "CampusNet"),
        os.path.dirname(command.strip('"')),
        os.environ.get("TEMP") or "",
    ]
    path = ""
    for target_dir in candidates:
        if not target_dir:
            continue
        try:
            os.makedirs(target_dir, exist_ok=True)
            candidate = os.path.join(target_dir, "connect-only.cmd")
            with open(candidate, "w", encoding="gbk", errors="replace") as fp:
                fp.write("@echo off\r\n")
                fp.write("rem Generated by CampusNet: silent auto-connect at logon.\r\n")
                fp.write("rem It connects, sends a toast, hands over to the main app, then exits.\r\n")
                fp.write(f'start "" {command}\r\n')
            path = candidate
            break
        except OSError:
            continue
    return path


def _enable_via_com() -> tuple[bool, str]:
    """用 Task Scheduler 的 COM 接口创建任务。

    为什么不用 ``schtasks /TR "\\"a b\\" c"``：那种**嵌套引号**经
    ``subprocess`` 的 argv 转换后会变成 ``\\"``，schtasks 解析出来是坏的路径
    （实测报 ``The system cannot find the path specified`` / ``Invalid argument/option``）。
    COM 接口一个字段一个值传，没有引号问题。

    用 **dynamic.Dispatch**（后期绑定）而不是 ``client.Dispatch``：
    后者会尝试把类型库生成到 ``%TEMP%\\gen_py``，在受限环境下会因拒绝访问而失败。
    """
    try:
        import tempfile
        cache_root = os.path.join(
            os.environ.get("LOCALAPPDATA") or tempfile.gettempdir(), "CampusNet"
        )
        try:
            os.makedirs(cache_root, exist_ok=True)
            os.environ["TEMP"] = cache_root
            os.environ["TMP"] = cache_root
        except OSError:
            pass
        from win32com.client import dynamic
    except Exception as exc:
        return False, f"缺少 pywin32：{exc}"

    exe = sys.executable if getattr(sys, "frozen", False) else os.path.join(
        os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
        "main.py",
    )
    program = exe if getattr(sys, "frozen", False) else sys.executable
    arguments = "--minimized" if getattr(sys, "frozen", False) else f'"{exe}" --minimized'
    try:
        service = dynamic.Dispatch("Schedule.Service")
        service.Connect()
        root = service.GetFolder("\\")

        definition = service.NewTask(0)
        definition.RegistrationInfo.Description = "校园网助手：登录后自动连接校园网"

        trigger = definition.Triggers.Create(9)
        trigger.UserId = os.environ.get("USERNAME") or ""
        trigger.Enabled = True

        definition.Principal.RunLevel = 1

        action = definition.Actions.Create(0)
        action.Path = program
        action.Arguments = arguments
        action.WorkingDirectory = os.path.dirname(program)

        root.RegisterTaskDefinition(TASK_NAME, definition, 6, None, None, 3)
        return True, "已通过 Task Scheduler 创建计划任务"
    except Exception as exc:
        return False, f"{type(exc).__name__}: {exc}"


def _enable_via_schtasks() -> tuple[bool, str]:
    """退路：schtasks 指向 .cmd 启动器（参数留空，避开引号问题）。"""
    script = launcher_script()
    if not script:
        return False, "无法生成启动脚本"
    line = f'schtasks /Create /TN "{TASK_NAME}" /TR "{script}" /SC ONLOGON /RL HIGHEST /F'
    try:
        proc = subprocess.run(["cmd.exe", "/c", line], capture_output=True, timeout=25)
    except (OSError, subprocess.SubprocessError) as exc:
        return False, f"{type(exc).__name__}: {exc}"
    raw = proc.stdout or proc.stderr or b""
    text = ""
    for encoding in ("gbk", "utf-8"):
        try:
            text = raw.decode(encoding)
            break
        except UnicodeDecodeError:
            continue
    return proc.returncode == 0, text.strip()[:200]


def _enable_via_schtasks_direct() -> tuple[bool, str]:
    """再一条退路：任务**只指向 exe、不带任何参数**。

    ``/TR`` 里带参数的路径会出现引号问题；不带参数时只有一个路径，交给 cmd 解析不会错。
    窗口是否隐藏交由程序自己的 ``start_minimized`` 设置决定（``--minimized`` 参数并非必需）。
    仅对打包后的 exe 有效。
    """
    if not getattr(sys, "frozen", False):
        return False, "源码方式必须带脚本路径参数，跳过"
    line = f'schtasks /Create /TN "{TASK_NAME}" /TR "{sys.executable} --connect-only" /SC ONLOGON /RL HIGHEST /F'
    try:
        proc = subprocess.run(["cmd.exe", "/c", line], capture_output=True, timeout=25)
    except (OSError, subprocess.SubprocessError) as exc:
        return False, f"{type(exc).__name__}: {exc}"
    raw = proc.stdout or proc.stderr or b""
    text = ""
    for encoding in ("gbk", "utf-8"):
        try:
            text = raw.decode(encoding)
            break
        except UnicodeDecodeError:
            continue
    return proc.returncode == 0, text.strip()[:200]


def enable() -> dict:
    """开启自启：COM 计划任务 → schtasks 计划任务 → Run 键（依次退让）。"""
    command, _cwd = launch_command()
    result = {"ok": False, "mechanism": "", "message": "", "command": command}
    ok, message = _enable_via_com()
    if ok and task_exists():
        result.update(ok=True, mechanism="task", message="已创建计划任务「CampusNet」：登录时以最高权限启动，不弹 UAC")
        remove_run_key()
        return result
    result["com_error"] = message
    ok, message = _enable_via_schtasks()
    if ok and task_exists():
        result.update(ok=True, mechanism="task", message="已创建计划任务「CampusNet」（schtasks 方式）")
        remove_run_key()
        return result
    result["task_error"] = message
    ok, direct_message = _enable_via_schtasks_direct()
    if ok and task_exists():
        result.update(ok=True, mechanism="task", message="已创建计划任务「CampusNet」（登录时以最高权限启动，不弹 UAC）")
        remove_run_key()
        return result
    result["direct_error"] = direct_message
    if _write_run_key(command):
        result.update(
            ok=True,
            mechanism="run",
            message="计划任务创建失败，已退回 Run 键。⚠ 本程序要求管理员权限，Run 键里的提权程序可能被系统跳过，建议以管理员身份运行本程序后再打开这个开关。",
        )
        return result
    result["message"] = f"各种方式都失败：{direct_message or message}"
    return result


def disable() -> dict:
    """关闭自启：计划任务与 Run 键都清掉。"""
    removed = []
    if task_exists():
        code, output = _schtasks("/Delete", "/TN", TASK_NAME, "/F")
        if code == 0:
            removed.append("计划任务")
        else:
            return {"ok": False, "message": f"删除计划任务失败：{output.strip()[:120]}"}
    if remove_run_key():
        removed.append("Run 键")
    return {"ok": True, "message": "已关闭开机自启" + (f"（清理了 {'、'.join(removed)}）" if removed else "")}


def _write_run_key(command: str) -> bool:
    try:
        import winreg
        with winreg.CreateKeyEx(winreg.HKEY_CURRENT_USER, RUN_KEY, 0, winreg.KEY_SET_VALUE) as key:
            winreg.SetValueEx(key, RUN_VALUE, 0, winreg.REG_SZ, command)
        return True
    except Exception:
        return False


def remove_run_key() -> bool:
    try:
        import winreg
        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, RUN_KEY, 0, winreg.KEY_SET_VALUE) as key:
            winreg.DeleteValue(key, RUN_VALUE)
        return True
    except FileNotFoundError:
        return False
    except Exception:
        return False
